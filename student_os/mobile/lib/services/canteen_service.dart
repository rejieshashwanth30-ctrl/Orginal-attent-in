  static CanteenOrder createOrder({
    required Canteen canteen,
    required List<CartItem> items,
    required PickupSlot pickupSlot,
    required String studentName,
    required String studentRollNumber,
    required String studentPhone,
    String paymentMethod = 'Campus Student Pay',
    String specialInstructions = '',
  }) {
    final subtotal = items.fold(0.0, (sum, i) => sum + i.totalPrice);
    final tax = double.parse((subtotal * 0.05).toStringAsFixed(2));
    final discount = subtotal >= 100 ? 15.0 : 0.0;
    final total = subtotal + tax - discount;

    final randomId = DateTime.now().millisecondsSinceEpoch % 10000;
    final tokenSuffix = (DateTime.now().millisecondsSinceEpoch % 90) + 10;
    final token = '${canteen.code}-$tokenSuffix';
    final orderNum = '#CAN-$randomId';

    final order = CanteenOrder(
      id: 'ord-${DateTime.now().millisecondsSinceEpoch}',
      orderNumber: orderNum,
      tokenNumber: token,
      canteenId: canteen.id,
      canteenName: canteen.name,
      canteenLocation: canteen.location,
      counterInfo: canteen.counterInfo,
      items: items.map((e) => CartItem(foodItem: e.foodItem, quantity: e.quantity, customizationNote: e.customizationNote)).toList(),
      subtotal: subtotal,
      tax: tax,
      discount: discount,
      totalAmount: total,
      pickupSlot: pickupSlot,
      status: OrderStatus.placed,
      orderedAt: DateTime.now(),
      estimatedReadyTime: DateTime.now().add(Duration(minutes: canteen.averagePrepMinutes)),
      studentName: studentName,
      studentRollNumber: studentRollNumber,
      studentPhone: studentPhone,
      paymentMethod: paymentMethod,
      specialInstructions: specialInstructions,
    );

    _orders.insert(0, order);
    return order;
  }

  static void advanceOrderStatus(String orderId) {
    final idx = _orders.indexWhere((o) => o.id == orderId);
    if (idx != -1) {
      final current = _orders[idx].status;
      switch (current) {
        case OrderStatus.placed:
          _orders[idx].status = OrderStatus.preparing;
          break;
        case OrderStatus.preparing:
          _orders[idx].status = OrderStatus.readyForPickup;
          break;
        case OrderStatus.readyForPickup:
          _orders[idx].status = OrderStatus.collected;
          break;
        case OrderStatus.collected:
        case OrderStatus.cancelled:
          break;
      }
    }
  }

  static void cancelOrder(String orderId) {
    final idx = _orders.indexWhere((o) => o.id == orderId);
    if (idx != -1 && _orders[idx].status == OrderStatus.placed) {
      _orders[idx].status = OrderStatus.cancelled;
    }
  }
